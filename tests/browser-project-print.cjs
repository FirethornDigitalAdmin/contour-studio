const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const url = process.env.APP_URL || 'http://127.0.0.1:5178';
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, acceptDownloads: true });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    await page.getByRole('heading', { name: 'A place worth making.' }).waitFor();
    const response = await page.request.get(`${url}/api/preset`);
    const settings = { ...await response.json(), name: 'UX print verification', project_type: 'single', width: 120, height: 90, resolution: 64, roads: 'none', buildings: false, water: false, forests: false, fields: false, railways: false, urban_spaces: false, landmarks: false, front_caption: false, multicolour: false, frame_mode: 'separate', joints: false, labels: false, layout: 'auto' };
    await page.locator('input[type=file][accept="application/json,.json"]').setInputFiles({ name: 'print-journey.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(settings)) });
    await page.getByRole('heading', { name: 'Make it yours.' }).waitFor();
    await page.getByRole('navigation', { name: 'Edit your artwork' }).getByRole('button', { name: 'Print', exact: true }).click();
    await page.getByRole('button', { name: 'Prepare print plates', exact: true }).click();
    await page.getByText('Your print pack is ready', { exact: true }).waitFor({ timeout: 180000 });
    await page.locator('.print-package').getByRole('button', { name: 'Open in Bambu Studio', exact: true }).waitFor();
    assert.equal(await page.locator('.print-package').getByRole('button', { name: 'Open in Bambu Studio', exact: true }).isEnabled(), true);
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('contour-studio.draft.v1')));
    const job = await (await page.request.get(`${url}/api/jobs/${saved.jobId}`)).json();
    assert.equal(job.result.settings.project_type, 'single');
    assert(job.result.parts.every(part => part.watertight));
    assert(job.result.parts.some(part => part.kind === 'frame'));
    const prepared = await page.request.post(`${url}/api/projects/${saved.jobId}/bambu?launch=false`, { data: {} });
    assert(prepared.ok(), await prepared.text());
    const plates = await prepared.json();
    assert(plates.plate_count >= 1);
    assert(plates.files.length >= 1);
    const project = await page.request.get(`${url}/api/files/${saved.jobId}/${plates.files[0]}`);
    assert(project.ok());
    assert((await project.body()).length > 1000);
    await page.locator('.print-package').scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'data/project-ux-review/print-ready.png' });
    await page.getByRole('navigation', { name: 'Edit your artwork' }).getByRole('button', { name: 'Design', exact: true }).click();
    await page.getByRole('button', { name: 'Frame', exact: true }).click();
    const frame = page.locator('.feature-group[data-feature="Frame & caption"]');
    await frame.getByText('Frame dimensions & profile', { exact: true }).click();
    await frame.getByRole('spinbutton', { name: 'Border width · mm', exact: true }).fill('12');
    await frame.getByRole('spinbutton', { name: 'Border width · mm', exact: true }).press('Tab');
    await page.getByRole('navigation', { name: 'Edit your artwork' }).getByRole('button', { name: 'Print', exact: true }).click();
    await page.getByRole('button', { name: 'Update print plates', exact: true }).waitFor();
    assert.equal(await page.locator('.print-package').getByRole('button', { name: 'Open in Bambu Studio', exact: true }).isEnabled(), false);
    await page.getByRole('button', { name: 'Update print plates', exact: true }).click();
    await page.getByText('Your print pack is ready', { exact: true }).waitFor({ timeout: 180000 });
    assert.equal(await page.locator('.print-package').getByRole('button', { name: 'Open in Bambu Studio', exact: true }).isEnabled(), true);
    assert.deepEqual(errors, []);
    fs.writeFileSync('data/project-ux-review/print-verification.json', JSON.stringify({ jobId: saved.jobId, plate_count: plates.plate_count, files: plates.files, parts: job.result.parts.map(part => ({ kind: part.kind, watertight: part.watertight })), errors }, null, 2));
    console.log('PASS: real UI generation, separate frame, watertight files, prepared Bambu plate download, stale editing guard and regeneration.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
